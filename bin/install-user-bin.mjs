#!/usr/bin/env node
import { existsSync, mkdirSync, writeFileSync, chmodSync, realpathSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = realpathSync(resolve(__dirname, ".."));
const node = realpathSync(process.execPath);

function expandHome(value) {
  return value.startsWith("~") ? join(homedir(), value.slice(1)) : value;
}

function arg(name, fallback) {
  const idx = process.argv.indexOf(name);
  return idx >= 0 && process.argv[idx + 1] ? process.argv[idx + 1] : fallback;
}

const binDir = resolve(expandHome(arg("--dir", process.env.GUSTAVE_USER_BIN_DIR ?? "~/.local/bin")));
const name = arg("--name", "gustave");
mkdirSync(binDir, { recursive: true });

const target = join(binDir, name);
const cli = join(root, "bin", "gustave.mjs");
if (!existsSync(cli)) throw new Error(`Cannot find Gustave CLI at ${cli}`);

const content = `#!/bin/sh
# Generated by Gustave. Uses absolute paths so local mise/pnpm/node_modules cannot hijack the runtime.
exec ${JSON.stringify(node)} ${JSON.stringify(cli)} "$@"
`;
writeFileSync(target, content);
chmodSync(target, 0o755);
console.log(`Installed ${target}`);
console.log(`Node: ${node}`);
console.log(`Gustave: ${cli}`);
console.log(`Add to PATH if needed: export PATH=${JSON.stringify(binDir)}:$PATH`);
